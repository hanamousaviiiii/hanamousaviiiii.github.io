"""Public machine-readable feeds for automations: /feed.xml, /api/content.json,
/sitemap.xml and /robots.txt.

Generated by gen.py on every build. These are not HTML pages, so they skip security.harden.
"""
import os, json, subprocess, html
from datetime import datetime, timezone, timedelta
from email.utils import format_datetime
import content

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SITE = 'https://aistudiohana.ir'
TITLE = 'hana.aistudio'
DESC = 'مجله‌ی آموزش هوش مصنوعی و تولید محتوا، نوشته‌ی هانا موسوی.'


def _parse_date(value):
    """Accept YYYY-MM-DD or an ISO datetime. Return an aware datetime, or None."""
    if not value or not isinstance(value, str):
        return None
    s = value.strip()
    try:
        if len(s) == 10 and s[4] == '-' and s[7] == '-':
            return datetime.fromisoformat(s).replace(tzinfo=timezone(timedelta(hours=3, minutes=30)))
        dt = datetime.fromisoformat(s.replace('Z', '+00:00'))
        return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)
    except ValueError:
        return None


def article_date(art):
    """Prefer an optional `date` field; otherwise the last git commit of the article file."""
    dt = _parse_date(art.get('date'))
    if dt:
        return dt
    path = os.path.join('content', 'articles', art['url'] + '.json')
    try:
        out = subprocess.check_output(
            ['git', 'log', '-1', '--format=%cI', '--', path],
            cwd=ROOT, text=True, stderr=subprocess.DEVNULL,
        ).strip()
        return _parse_date(out)
    except Exception:
        return None


def _sorted_articles():
    """Newest first (date, then higher `order`). Published-only; content.folder already filters."""
    rows = []
    for a in content.folder('articles'):
        rows.append((article_date(a), a))
    rows.sort(key=lambda r: (
        r[0] or datetime(1970, 1, 1, tzinfo=timezone.utc),
        float(r[1].get('order') or 0),
    ), reverse=True)
    return rows


def _abs(path):
    return SITE + '/' + path.lstrip('/')


def write_rss(rows, built):
    items = []
    for dt, a in rows:
        link = _abs(f"articles/{a['url']}.html")
        pub = f'    <pubDate>{html.escape(format_datetime(dt))}</pubDate>\n' if dt else ''
        tag = a.get('tag') or ''
        cat = f'    <category>{html.escape(tag)}</category>\n' if tag else ''
        items.append(
            '  <item>\n'
            f'    <title>{html.escape(a.get("title") or "")}</title>\n'
            f'    <link>{html.escape(link)}</link>\n'
            f'    <guid isPermaLink="true">{html.escape(link)}</guid>\n'
            f'    <description>{html.escape(a.get("description") or "")}</description>\n'
            f'{pub}{cat}'
            '  </item>'
        )
    last = format_datetime(built)
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">\n'
        '<channel>\n'
        f'  <title>{html.escape(TITLE)}</title>\n'
        f'  <link>{html.escape(_abs("blog.html"))}</link>\n'
        f'  <description>{html.escape(DESC)}</description>\n'
        '  <language>fa-IR</language>\n'
        f'  <lastBuildDate>{html.escape(last)}</lastBuildDate>\n'
        f'  <atom:link href="{html.escape(_abs("feed.xml"))}" rel="self" type="application/rss+xml"/>\n'
        + '\n'.join(items) + '\n'
        '</channel>\n'
        '</rss>\n'
    )
    path = os.path.join(ROOT, 'feed.xml')
    open(path, 'w', encoding='utf-8').write(xml)
    print('wrote feed.xml')


def write_api(rows, built):
    articles = []
    for dt, a in rows:
        articles.append({
            'url': a['url'],
            'title': a.get('title') or '',
            'description': a.get('description') or '',
            'minutes': a.get('minutes') or '',
            'tag': a.get('tag') or '',
            'cover': a.get('cover') or 'a1',
            'image': content.media_path(a.get('image')),
            'order': a.get('order'),
            'date': dt.date().isoformat() if dt else None,
            'path': f"/articles/{a['url']}.html",
            'href': _abs(f"articles/{a['url']}.html"),
            'body': a.get('body') or '',
        })

    works = content.load('works.json', {'settings': {}, 'chapters': []})
    settings = works.get('settings') or {}
    chapters = []
    for c in works.get('chapters') or []:
        if not c.get('visible', True):
            continue
        items = []
        for it in c.get('items') or []:
            if it.get('visible') is False:
                continue
            items.append({
                'kind': it.get('kind') or '',
                'title': it.get('title') or '',
                'student': it.get('student') or '',
                'file': content.media_path(it.get('file')),
                'poster': content.media_path(it.get('poster')),
                'shape': it.get('shape') or '',
            })
        slug = c.get('slug') or ''
        chapters.append({
            'slug': slug,
            'title': c.get('title') or '',
            'latin': c.get('latin') or '',
            'num': c.get('num') or '',
            'icon': c.get('icon') or 'spark',
            'href': _abs('student-works.html') + ('?ch=' + slug if slug else ''),
            'count': len(items),
            'items': items,
        })

    site = content.site()
    courses_out = []
    for c in content.courses(True):
        chs = []
        for i, ch in enumerate(c.get('chapters') or [], 1):
            slug = ch.get('slug') or ''
            chs.append({
                'slug': slug,
                'num': i,
                'title': ch.get('title') or '',
                'summary': ch.get('summary') or '',
                'outcomes': ch.get('outcomes') or [],
                'path': f'/chapters/{slug}.html' if slug else '',
                'href': _abs(f'chapters/{slug}.html') if slug else '',
            })
        courses_out.append({
            'id': c['id'],
            'name': c['name'],
            'path': f"/courses/{c['id']}.html",
            'href': _abs(f"courses/{c['id']}.html"),
            'chapters': chs,
        })
    payload = {
        'generated': built.isoformat(),
        'site': {
            'name': TITLE,
            'url': SITE,
            'blog': _abs('blog.html'),
            'feed': _abs('feed.xml'),
            'instagram': site.get('instagram') or '',
            'telegram': site.get('telegram') or '',
        },
        'articles': articles,
        'courses': courses_out,
        'works': {
            'settings': {
                'tile_shape': settings.get('tile_shape') or 'auto',
                'show_student': settings.get('show_student', True),
                'empty_label': settings.get('empty_label') or 'نمونه‌کار هنرجو',
            },
            'chapters': chapters,
        },
    }
    out_dir = os.path.join(ROOT, 'api')
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, 'content.json')
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write('\n')
    print('wrote api/content.json')


_SKIP_DIRS = {
    'admin', '_drafts', '_build', '_site', 'content', 'apps-script',
    'assets', 'api', 'screenshots', '__pycache__', '.git', '.github',
}
_SKIP_FILES = {'404.html'}

# Content sources used to date a public HTML page when git history of the
# HTML itself is missing or older than the JSON that generated it.
_CONTENT_SOURCES = {
    'index.html': ['content/home.json', 'content/site.json', 'content/testimonials.json'],
    'blog.html': ['content/articles'],
    'course.html': ['content/courses.json'],
    'challenge.html': ['content/courses.json'],
    'links.html': ['content/links.json'],
    'contact.html': ['content/site.json'],
    'ai-faq.html': ['content/ai-faq.json', 'content/faq'],
    'student-works.html': ['content/works.json'],
}


def _public_pages():
    """Relative paths of public HTML pages (index.html first). Excludes admin, drafts, 404."""
    pages = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        rel_dir = os.path.relpath(dirpath, ROOT)
        parts = [] if rel_dir == '.' else rel_dir.split(os.sep)
        if any(p in _SKIP_DIRS or p.startswith('.') for p in parts):
            dirnames[:] = []
            continue
        dirnames[:] = [d for d in dirnames if d not in _SKIP_DIRS and not d.startswith('.')]
        for fn in filenames:
            if not fn.endswith('.html') or fn in _SKIP_FILES:
                continue
            rel = fn if rel_dir == '.' else os.path.join(rel_dir, fn)
            pages.append(rel.replace(os.sep, '/'))
    pages.sort(key=lambda p: (p != 'index.html', p))
    return pages


def _sources_for(rel):
    srcs = [rel]
    if rel in _CONTENT_SOURCES:
        srcs.extend(_CONTENT_SOURCES[rel])
    elif rel.startswith('articles/') and rel.endswith('.html'):
        srcs.append(os.path.join('content', 'articles', rel[9:-5] + '.json'))
    elif rel.startswith('courses/') and rel.endswith('.html'):
        srcs.append('content/courses.json')
    elif rel.startswith('chapters/') and rel.endswith('.html'):
        srcs.append('content/courses.json')
    elif rel.startswith('faq/') and rel.endswith('.html'):
        srcs.append(os.path.join('content', 'faq', rel[4:-5] + '.json'))
        srcs.append('content/ai-faq.json')
    return srcs


def _git_lastmod(*paths):
    latest = None
    for path in paths:
        try:
            out = subprocess.check_output(
                ['git', 'log', '-1', '--format=%cI', '--', path],
                cwd=ROOT, text=True, stderr=subprocess.DEVNULL,
            ).strip()
            dt = _parse_date(out)
            if dt and (latest is None or dt > latest):
                latest = dt
        except Exception:
            pass
    return latest


def write_sitemap(article_dates, built):
    urls = []
    for rel in _public_pages():
        loc = SITE + '/' if rel == 'index.html' else _abs(rel)
        slug = rel[9:-5] if rel.startswith('articles/') and rel.endswith('.html') else None
        dt = (article_dates.get(slug) if slug else None) or _git_lastmod(*_sources_for(rel)) or built
        lastmod = dt.date().isoformat()
        urls.append(
            '  <url>\n'
            f'    <loc>{html.escape(loc)}</loc>\n'
            f'    <lastmod>{html.escape(lastmod)}</lastmod>\n'
            '  </url>'
        )
    xml = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + '\n'.join(urls) + '\n'
        '</urlset>\n'
    )
    path = os.path.join(ROOT, 'sitemap.xml')
    open(path, 'w', encoding='utf-8').write(xml)
    print('wrote sitemap.xml (%d urls)' % len(urls))


def write_robots():
    text = (
        'User-agent: *\n'
        'Allow: /\n'
        'Disallow: /admin/\n'
        '\n'
        f'Sitemap: {_abs("sitemap.xml")}\n'
    )
    path = os.path.join(ROOT, 'robots.txt')
    open(path, 'w', encoding='utf-8').write(text)
    print('wrote robots.txt')


def write():
    rows = _sorted_articles()
    built = datetime.now(timezone.utc).replace(microsecond=0)
    write_rss(rows, built)
    write_api(rows, built)
    article_dates = {a['url']: dt for dt, a in rows if dt}
    write_sitemap(article_dates, built)
    write_robots()
