# Builds every page from _build/*.py templates + content/*.json (the admin panel edits content/).
# Run: python3 _build/gen.py     (GitHub Actions runs it on every push, see .github/workflows/deploy.yml)
import sys, os, glob, json
sys.path.insert(0, os.path.dirname(__file__))
import content, security
import page_index, page_course, page_misc, page_challenge, page_faq, page_works
OUT = os.path.join(os.path.dirname(__file__), '..')

def w(p, build, *a):
    content.CURRENT = p
    s = security.harden(build(*a), p)
    os.makedirs(os.path.dirname(os.path.join(OUT, p)) or OUT, exist_ok=True)
    open(os.path.join(OUT, p), 'w', encoding='utf-8').write(s); print('wrote', p)

def clean(folder, keep):
    # remove pages whose article was deleted in the admin panel
    for f in glob.glob(os.path.join(OUT, folder, '*.html')):
        if os.path.splitext(os.path.basename(f))[0] not in keep:
            os.remove(f); print('removed', os.path.relpath(f, OUT))

def data_js():
    # course data for course.html and the challenge result (same source as the HTML pages)
    q = lambda v: json.dumps(v, ensure_ascii=False)
    out = '/* Course data — used by course.html, challenge result and forms.\n   Generated by _build/gen.py from content/courses.json (edit in the admin panel). */\nwindow.HANA_COURSES = {\n'
    rows = []
    for c in content.courses():
        f = [('id', c['id']), ('name', c['name']), ('latin', c.get('latin', '')), ('numeral', c.get('num', '')),
             ('subtitle', c.get('js_subtitle') or c.get('page_sub', '')), ('price', c.get('price', '')),
             ('teaser', c.get('js_teaser') or c.get('card_sub', '')), ('perks', c.get('js_perks') or []), ('syllabus', c.get('syllabus') or [])]
        body = ',\n'.join(f'    {k}: {q(v)}' for k, v in f)
        rows.append(f'  {q(c["id"])}: {{\n{body}\n  }}')
    open(os.path.join(OUT, 'assets', 'js', 'data.js'), 'w', encoding='utf-8').write(out + ',\n'.join(rows) + '\n};\n'); print('wrote assets/js/data.js')

w('index.html', page_index.build)
w('course.html', page_course.build)
w('challenge.html', page_challenge.build)
w('blog.html', page_misc.blog)
w('links.html', page_misc.links)
w('contact.html', page_misc.contact)
for i, a in enumerate(page_misc.ARTS):
    w(f'articles/{a[0]}.html', page_misc.article, i)
clean('articles', [a[0] for a in page_misc.ARTS])
w('ai-faq.html', page_faq.hub)
for i, f in enumerate(page_faq.FAQ):
    w(f'faq/{f[0]}.html', page_faq.article, i)
clean('faq', [f[0] for f in page_faq.FAQ])
w('student-works.html', page_works.build)
data_js()
